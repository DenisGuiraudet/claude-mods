// Builds the mod's world module from the lab sources, so the lab and the mod draw the same thing.
// Usage: node mod.js <lab dir> <mod hooks dir>
const fs = require('fs'), path = require('path');
const lab = path.resolve(process.argv[2]), out = path.resolve(process.argv[3]);
fs.mkdirSync(path.join(out, 'data'), { recursive: true });

// data: the lab's `const X=...` files become `export const X=...` modules
for (const [file, name] of [['baked.js', 'BAKED'], ['atlas.js', 'ATLAS'], ['actors.js', 'ACTORS']]) {
  const src = fs.readFileSync(path.join(lab, file), 'utf8').replace(new RegExp(`^const ${name}=`, 'm'), `export const ${name}=`);
  fs.writeFileSync(path.join(out, 'data', file), src);
}

let engine = fs.readFileSync(path.join(lab, 'engine.js'), 'utf8').replace(/^'use strict';\n/, '');
// the lab warns about a tile missing from the atlas; the mod has no console to warn on
engine = engine.replace(/if\(A&&!tileDefs\.miss\?\.has\(id\)\)\{[^}]*\}/, '');
const view = fs.readFileSync(path.join(lab, 'view-valley.js'), 'utf8');

const head = `// Generated by build/mod.js from the lab (engine.js + view-valley.js). Edit the lab, then rebuild.
// La Vallée: a pixel-art village that lives at the pace of the Claude Code session.
// Tiles: Kenney Tiny Town, Tiny Dungeon, Tiny Farm (CC0). Actors: Ninja Adventure by Pixel-boy and AAA (CC0).
import { BAKED } from './data/baked.js';
import { ATLAS } from './data/atlas.js';
import { ACTORS } from './data/actors.js';
const SHEETS = {};
`;
const tail = `
export { S, W, MODELS, EFFORT, SIG, VIEWS, derive, newWorld, step, retarget, wake, compose, ambient,
  evPrompt, evError, evCompact, evMerge, evCommit, evPush, sigActive, sigValue, sigCol, progress };
`;
fs.writeFileSync(path.join(out, 'world.js'), head + engine + '\n' + view + tail);
console.log('world.js', fs.statSync(path.join(out, 'world.js')).size, 'bytes');
